"""Query the import index: which modules does a statement need?

    index = ImportIndex("import_index.sqlite")
    plan = index.plan_for_source(lean_statement_text)
    plan.import_lines()        # "import StacksFrontier.X\\nimport Mathlib.Y"
    plan.loaded_size           # modules Lean loads for those imports

Resolution is lexical (the same approximation as `shape.py`): identifiers that are not bound are
taken to be constants, tried against the open namespaces. Three things it cannot see, so the
caller must treat a plan as a *proposal* and re-check the elaborated statement:

* notation, coercions and instances: they live in modules no constant names;
* names generated by tactics or attributes (`to_additive`, `simps`, structure eta);
* dot notation on a variable (`h.foo`), whose namespace depends on its type.

Two closures, because Lean 4.35 distinguishes them. The *visible* closure follows only `public`
imports: a plain `import` inside a dependency does not re-export its declarations, so a name
defined there is not available downstream. The *loaded* closure follows every edge: that is
what Lean reads from disk (measured: `allImportedModuleNames` of a Mathlib import equals it to
within 2 modules), so it is the one that costs time and memory.
"""

from __future__ import annotations

import re
import sqlite3
from collections import defaultdict
from collections.abc import Iterable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from tools.stacks_index.shape import query_shape

# When one name is defined in several layers, reviewed code beats unreviewed Frontier code.
LAYER_PRIORITY = ("core", "mathlib", "dep", "lean", "frontier")
_OPEN = re.compile(r"^[ \t]*(?:open|export)\s+(?P<body>[^\n]*)", re.MULTILINE)
_NAMESPACE = re.compile(r"^[ \t]*namespace\s+(?P<name>[A-Za-z_][\w.']*)", re.MULTILINE)
_IMPORT_LINE = re.compile(r"^[ \t]*import\s+(?:all\s+)?(?P<name>[A-Za-z_][\w.']*)", re.MULTILINE)
_OPEN_STOP = {"in", "scoped", "hiding", "renaming"}
_TYPE_KINDS = frozenset({"structure", "class", "inductive"})


@dataclass(frozen=True, slots=True)
class Location:
    name: str
    module: str
    layer: str
    kind: str


@dataclass(slots=True)
class ImportPlan:
    imports: list[str]  # irredundant direct imports
    closure: frozenset[str]  # modules whose declarations are visible (public edges)
    loaded: frozenset[str]  # modules Lean loads (every edge); what costs time and memory
    loaded_by_layer: dict[str, int]
    resolved: dict[str, Location]  # written identifier -> chosen definition
    unresolved: list[str]
    ambiguous: dict[str, list[Location]]
    via_prefix: dict[str, str]
    weak: dict[str, list[Location]]  # tail-name matches (dot notation); the cheapest is imported
    namespace_added: dict[str, str]  # opened namespace no chosen import declares -> module added
    conflicts: list[tuple[str, list[str]]]  # names defined in more than one loaded module
    visibility: str = "public"
    notes: list[str] = field(default_factory=list)

    @property
    def closure_size(self) -> int:
        return len(self.closure)

    @property
    def loaded_size(self) -> int:
        return len(self.loaded)

    @property
    def frontier_modules(self) -> list[str]:
        return sorted(m for m in self.loaded if m.startswith("StacksFrontier"))

    @property
    def stacks_modules(self) -> list[str]:
        """Loaded modules from StacksCore or StacksFrontier: the ones that must be built."""
        return sorted(m for m in self.loaded if m.startswith(("StacksFrontier", "StacksCore")))

    @property
    def trust_level(self) -> str:
        """Lowest trust among the layers whose constants the statement names directly."""
        layers = {loc.layer for loc in self.resolved.values()}
        if "frontier" in layers:
            return "frontier"
        if "core" in layers:
            return "core"
        return "mathlib"

    def import_lines(self) -> str:
        return "\n".join(f"import {module}" for module in self.imports)


class ImportIndex:
    def __init__(self, path: str | Path) -> None:
        self.path = Path(path)
        self.db = sqlite3.connect(f"file:{self.path}?mode=ro", uri=True)
        self._load_graph()

    # -- graph ---------------------------------------------------------------------------
    def _load_graph(self) -> None:
        self.module_id: dict[str, int] = {}
        self.module_name: dict[int, str] = {}
        self.layer: dict[int, str] = {}
        for identifier, name, layer in self.db.execute("SELECT id, name, layer FROM module"):
            self.module_id[name] = identifier
            self.module_name[identifier] = name
            self.layer[identifier] = layer
        public: dict[int, list[int]] = defaultdict(list)
        every: dict[int, list[int]] = defaultdict(list)
        for src, dst, is_public in self.db.execute("SELECT src, dst, public FROM edge"):
            every[src].append(dst)
            if is_public:
                public[src].append(dst)
        self._edges = {"public": public, "all": every}
        self._bits_memo: dict[str, dict[int, int]] = {"public": {}, "all": {}}

    def manifest(self) -> dict[str, Any]:
        return {key: value for key, value in self.db.execute("SELECT key, value FROM meta")}

    def direct_imports(self, module: str) -> list[tuple[str, bool]]:
        identifier = self.module_id[module]
        return [
            (self.module_name[dst], bool(public))
            for dst, public in self.db.execute(
                "SELECT dst, public FROM edge WHERE src = ? ORDER BY dst", (identifier,)
            )
        ]

    def closure_of(self, modules: Iterable[str], visibility: str = "public") -> frozenset[str]:
        """Modules Lean loads for `import m` of each m in `modules` (the roots included)."""
        ids = [self.module_id[m] for m in modules if m in self.module_id]
        return frozenset(self.module_name[i] for i in self._closure_ids(ids, visibility))

    def _bits(self, root: int, visibility: str) -> int:
        """The closure of one module as a bitset over module ids (memoized, built lazily)."""
        memo = self._bits_memo[visibility]
        if root in memo:
            return memo[root]
        edges = self._edges[visibility]
        stack = [root]
        visiting: set[int] = set()
        while stack:
            node = stack[-1]
            if node in memo:
                stack.pop()
                continue
            visiting.add(node)
            pending = [d for d in edges.get(node, ()) if d not in memo and d not in visiting]
            if pending:
                stack.extend(pending)
                continue
            bits = 1 << node
            for dependency in edges.get(node, ()):
                bits |= memo.get(dependency, 0)
            memo[node] = bits
            visiting.discard(node)
            stack.pop()
        return memo[root]

    def _union_bits(self, roots: Iterable[int], visibility: str) -> int:
        bits = 0
        for root in roots:
            bits |= self._bits(root, visibility)
        return bits

    @staticmethod
    def _ids(bits: int) -> frozenset[int]:
        text = bin(bits)[:1:-1]
        return frozenset(i for i, char in enumerate(text) if char == "1")

    def _closure_ids(self, roots: Iterable[int], visibility: str) -> frozenset[int]:
        return self._ids(self._union_bits(roots, visibility))

    def _root_closure(self, root: int, visibility: str) -> frozenset[int]:
        return self._ids(self._bits(root, visibility))

    # -- declarations ----------------------------------------------------------------------
    def locate(self, name: str) -> list[Location]:
        rows = self.db.execute(
            "SELECT d.name, m.name, m.layer, d.kind FROM decl d JOIN module m ON m.id = d.module"
            " WHERE d.name = ?",
            (name,),
        ).fetchall()
        return [Location(*row) for row in rows]

    def equivalents(self, name: str) -> list[Location]:
        """Declarations in another layer whose statement text is identical (a same-meaning hint)."""
        rows = self.db.execute(
            "SELECT e2.name, e2.module, e2.layer FROM equivalent e1 JOIN equivalent e2"
            " ON e1.type_hash = e2.type_hash WHERE e1.name = ? AND e2.name != e1.name",
            (name,),
        ).fetchall()
        return [Location(n, m, layer, "?") for n, m, layer in rows]

    def resolve(
        self, identifier: str, opens: Iterable[str] = (), namespaces: Iterable[str] = ()
    ) -> tuple[list[Location], str | None]:
        """Definitions an identifier written in a statement may refer to.

        Tries `ns.identifier` for each enclosing namespace and open namespace, then the bare
        name. A name with no match falls back to its longest declared prefix that is a
        structure, class or inductive (a field or constructor lives with its type). Returns
        (hits, prefix); `prefix` is the type the hit stands for, or None for an exact hit.
        """
        scopes = [*dict.fromkeys([*_chain(namespaces), *opens]), ""]
        candidates = [f"{scope}.{identifier}" if scope else identifier for scope in scopes]
        candidates = list(dict.fromkeys(candidates))
        hits: list[Location] = []
        for candidate in candidates:
            hits.extend(self.locate(candidate))
        if hits:
            return hits, None
        for candidate in candidates:
            parts = candidate.split(".")
            for end in range(len(parts) - 1, 0, -1):
                head = ".".join(parts[:end])
                typed = [h for h in self.locate(head) if h.kind in _TYPE_KINDS]
                if typed:
                    return typed, head
        return [], None

    def weak_candidates(self, identifier: str, limit: int = 3) -> list[Location]:
        """Declarations whose last name component is `identifier`: field or dot notation.

        `U.IdealSheafData` with `U : Scheme` is written with the bare tail; only the type of `U`
        says which namespace it belongs to. Returns [] when more than `limit` declarations match,
        since then the tail alone says too little.
        """
        tail = identifier.rsplit(".", 1)[-1]
        rows = self.db.execute(
            "SELECT d.name, m.name, m.layer, d.kind FROM decl d JOIN module m ON m.id = d.module"
            " WHERE d.short = ? LIMIT ?",
            (tail, limit + 1),
        ).fetchall()
        return [Location(*row) for row in rows] if len(rows) <= limit else []

    # -- planning --------------------------------------------------------------------------
    def plan(
        self,
        identifiers: Iterable[str],
        opens: Iterable[str] = (),
        namespaces: Iterable[str] = (),
        *,
        visibility: str = "public",
        extra_modules: Iterable[str] = (),
        include_weak: bool = True,
    ) -> ImportPlan:
        resolved: dict[str, Location] = {}
        unresolved: list[str] = []
        ambiguous: dict[str, list[Location]] = {}
        via_prefix: dict[str, str] = {}
        weak: dict[str, list[Location]] = {}
        pending: dict[str, list[Location]] = {}
        opens = list(opens)
        for identifier in dict.fromkeys(identifiers):
            hits, prefix = self.resolve(identifier, opens, namespaces)
            if not hits:
                guesses = self.weak_candidates(identifier)
                if guesses:
                    weak[identifier] = guesses
                else:
                    unresolved.append(identifier)
                continue
            if prefix:
                via_prefix[identifier] = prefix
            distinct = {(h.name, h.module) for h in hits}
            if len(distinct) > 1:
                ambiguous[identifier] = sorted(hits, key=lambda h: (h.name, h.module))
                pending[identifier] = hits
                continue
            resolved[identifier] = hits[0]
        # A name defined in several modules: take the one an unambiguous constant already
        # makes visible, else the most trusted layer.
        visible_bits = self._union_bits(
            (self.module_id[loc.module] for loc in resolved.values()), visibility
        )
        for identifier, hits in pending.items():
            inside = [h for h in hits if visible_bits >> self.module_id[h.module] & 1]
            resolved[identifier] = min(inside or hits, key=_priority)
        modules = {loc.module for loc in resolved.values()} | set(extra_modules)
        if include_weak:
            # a tail with several candidates says too little about the namespace: take the one
            # with the smallest closure (cheapest to be wrong about); `weak` lists all of them
            for guesses in weak.values():
                cheapest = min(
                    guesses,
                    key=lambda g: (
                        self._bits(self.module_id[g.module], visibility).bit_count(),
                        g.module,
                    ),
                )
                modules.add(cheapest.module)
        namespace_added: dict[str, str] = {}
        for namespace in dict.fromkeys(opens):
            added = self._ensure_namespace(namespace, modules, visibility)
            if added:
                namespace_added[namespace] = added
                modules.add(added)
        direct = self._irredundant(modules, visibility)
        direct_ids = [self.module_id[m] for m in direct]
        closure_ids = self._closure_ids(direct_ids, visibility)
        loaded_ids = self._closure_ids(direct_ids, "all")
        by_layer: dict[str, int] = defaultdict(int)
        for module_id in loaded_ids:
            by_layer[self.layer[module_id]] += 1
        return ImportPlan(
            imports=direct,
            closure=frozenset(self.module_name[i] for i in closure_ids),
            loaded=frozenset(self.module_name[i] for i in loaded_ids),
            loaded_by_layer=dict(sorted(by_layer.items())),
            resolved=resolved,
            unresolved=unresolved,
            ambiguous=ambiguous,
            via_prefix=via_prefix,
            weak=weak,
            namespace_added=namespace_added,
            conflicts=self._conflicts_in(closure_ids),
            visibility=visibility,
        )

    def plan_for_source(self, source: str, *, visibility: str = "public") -> ImportPlan:
        """Plan for a Lean statement: uses its `open`/`namespace` lines and its own imports."""
        shape = query_shape(_strip_header(source))
        identifiers = [*shape["conclusion_constants"], *shape["hypothesis_constants"]]
        opens = [n for body in _OPEN.findall(source) for n in _open_names(body)]
        namespaces = _NAMESPACE.findall(source)
        return self.plan(identifiers, opens, namespaces, visibility=visibility)

    def namespace_modules(self, namespace: str) -> list[str]:
        """Modules that declare something under `namespace.`."""
        rows = self.db.execute("SELECT module FROM namespace WHERE name = ?", (namespace,))
        return [self.module_name[r[0]] for r in rows.fetchall()]

    def _ensure_namespace(self, namespace: str, modules: set[str], visibility: str) -> str | None:
        """`open N` fails with `unknown namespace` unless a visible module declares under N.

        Returns the module to add (the declaring module with the smallest closure), or None when
        the current imports already declare the namespace or no indexed module does.
        """
        known = [m for m in modules if m in self.module_id]
        visible_bits = self._union_bits((self.module_id[m] for m in known), visibility)
        candidates = self.namespace_modules(namespace)
        if not candidates or any(visible_bits >> self.module_id[m] & 1 for m in candidates):
            return None
        # An opened namespace only has to exist, so never pull in unreviewed code for it when a
        # reviewed module declares the namespace too.
        return min(
            candidates,
            key=lambda m: (
                self.layer[self.module_id[m]] == "frontier",
                self._bits(self.module_id[m], visibility).bit_count(),
                m,
            ),
        )

    def _irredundant(self, modules: set[str], visibility: str) -> list[str]:
        known = sorted(m for m in modules if m in self.module_id)
        bits = {m: self._bits(self.module_id[m], visibility) for m in known}
        keep = [
            m
            for m in known
            if not any(other != m and bits[other] >> self.module_id[m] & 1 for other in known)
        ]
        return keep

    def _conflicts_in(self, closure_ids: frozenset[int]) -> list[tuple[str, list[str]]]:
        """Names defined in two loaded modules: Lean would refuse that file."""
        found: list[tuple[str, list[str]]] = []
        rows = self.db.execute("SELECT name, modules FROM conflict").fetchall()
        import json

        for name, modules in rows:
            loaded = [m for m in json.loads(modules) if self.module_id.get(m) in closure_ids]
            if len(loaded) > 1:
                found.append((name, loaded))
        return found

    def own_imports_closure(self, source: str, visibility: str = "public") -> frozenset[str]:
        """Modules the statement's *own* import lines load (the baseline to compare with)."""
        modules = _IMPORT_LINE.findall(source)
        return self.closure_of(modules, visibility)


def _priority(location: Location) -> tuple[int, str]:
    order = LAYER_PRIORITY.index(location.layer) if location.layer in LAYER_PRIORITY else 99
    return order, location.module


def _chain(namespaces: Iterable[str]) -> list[str]:
    chain: list[str] = []
    for namespace in namespaces:
        parts = namespace.split(".")
        chain.extend(".".join(parts[:i]) for i in range(len(parts), 0, -1))
    return chain


def _open_names(body: str) -> list[str]:
    body = re.sub(r"\([^)]*\)", " ", body)
    return [token for token in re.findall(r"[A-Za-z_][\w.']*", body) if token not in _OPEN_STOP]


def _strip_header(source: str) -> str:
    lines = [
        line
        for line in source.splitlines()
        if not re.match(r"\s*(?:import|open|universe|namespace|section|end|set_option)\b", line)
    ]
    return "\n".join(lines)


def plan_summary(plan: ImportPlan) -> dict[str, Any]:
    """A plan without the statement text: identifiers and module names only."""
    return {
        "imports": plan.imports,
        "visible_modules": plan.closure_size,
        "loaded_modules": plan.loaded_size,
        "loaded_by_layer": plan.loaded_by_layer,
        "stacks_modules_loaded": len(plan.stacks_modules),
        "frontier_modules_loaded": len(plan.frontier_modules),
        "trust_level": plan.trust_level,
        "unresolved": plan.unresolved,
        "weak": {k: [loc.module for loc in v] for k, v in plan.weak.items()},
        "ambiguous": sorted(plan.ambiguous),
        "namespace_added": plan.namespace_added,
        "conflicts_in_closure": len(plan.conflicts),
    }


def main(argv: list[str] | None = None) -> int:
    import argparse
    import json

    parser = argparse.ArgumentParser(description="Minimal imports for a Lean statement.")
    parser.add_argument("--index", type=Path, required=True)
    parser.add_argument("--source", type=Path, required=True, help="Lean file with the statement")
    args = parser.parse_args(argv)
    index = ImportIndex(args.index)
    plan = index.plan_for_source(args.source.read_text())
    print(json.dumps(plan_summary(plan), ensure_ascii=False, indent=2))
    return 0


